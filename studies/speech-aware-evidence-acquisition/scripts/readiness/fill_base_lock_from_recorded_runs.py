from typing import Any

REPO = Path(__file__).resolve().parents[2]
DEFAULT_LOCK = REPO / "docs/readiness/2026-10-29-engineering-base-lock-npu-port-v1/base-lock-v1.json"
DEFAULT_S8 = REPO / "docs/results/2026-10-29-npu-port-synthetic-speed-baseline-v1.md"
RECEIPT_SCHEMA = "saea-base-lock-fill-receipt-v1"
LOCK_SCHEMA = "saea-engineering-base-lock-v1"
PLACEHOLDER = "TODO-R0:"
EXPECTED_CHECKS = 11
R0_STEPS = ("gate-cards", "disk", "deploy-up", "health", "deploy-status", "startup-lines", "receipt", "verify-base",
            "smoke", "manifest")
BOOTSTRAP_STEPS = R0_STEPS[:R0_STEPS.index("receipt") + 1]
REL_TOL = {"kv_tokens": 0.01, "max_concurrency": 0.01}  # the verifier's KV_REL_TOL leaves
NOT_COMPARED = ("_skeleton", "record")  # keys the verifier never compares
BEGIN = "<!-- BEGIN recorded-runs table: generated by scripts/readiness/fill_base_lock_from_recorded_runs.py; do not edit -->"
END = "<!-- END recorded-runs table -->"
S8_ANCHOR = "Branch (ii)/(iii)/(iv) of plan 3.10"
S8_SECTION = "## 1. Recorded table"
SAYS = ": base-lock says "


class Refused(Exception):
    """The inputs do not allow a fill; nothing is written."""


# ---------------------------------------------------------------- small pure helpers
def sha256_bytes(raw: bytes) -> str:
    return hashlib.sha256(raw).hexdigest()


def canonical(doc: Any) -> str:
    return json.dumps(doc, indent=2, sort_keys=True, ensure_ascii=True) + "\n"


def is_placeholder(value: Any) -> bool:
    return isinstance(value, str) and value.startswith(PLACEHOLDER)


def leaves(doc: Any, prefix: tuple[str, ...] = ()):
    """(path, value) of every leaf; lists are leaf values, as in the verifier's claims."""
    if isinstance(doc, dict) and doc:
        for key in sorted(doc):
            yield from leaves(doc[key], prefix + (key,))
    else:
        yield prefix, doc


def lookup(doc: Any, path: tuple[str, ...]) -> Any:
    for key in path:
        if not isinstance(doc, dict) or key not in doc:
            raise KeyError(path)
        doc = doc[key]
    return doc


def assign(doc: dict, path: tuple[str, ...], value: Any) -> None:
    node = doc
    for key in path[:-1]:
        node = node[key]
    node[path[-1]] = value


def show(path: tuple[str, ...]) -> str:
    return " > ".join(path)


def values_equal(path: tuple[str, ...], expected: Any, observed: Any) -> bool:
    """The verifier's comparison: equality, with a relative tolerance on kv_tokens and max_concurrency."""
    tol = REL_TOL.get(path[-1]) if path else None
    numbers = (int, float)
    if tol is not None and isinstance(expected, numbers) and not isinstance(expected, bool) \
            and isinstance(observed, numbers) and not isinstance(observed, bool):
        return abs(observed - expected) <= tol * abs(expected)
    return expected == observed


def other_profile(path: tuple[str, ...], profile_id: str) -> bool:
    return len(path) >= 2 and path[0] == "profiles" and path[1] != profile_id


# ---------------------------------------------------------------- inputs
class Inputs:
    """Every file read, with its sha256 (the receipt's input list)."""

    def __init__(self) -> None:
        self.hashes: dict[str, str] = {}

    def raw(self, path: Path) -> bytes:
        data = path.read_bytes()
        self.hashes[str(path)] = sha256_bytes(data)
        return data

    def json(self, path: Path, what: str) -> Any:
        try:
            return json.loads(self.raw(path).decode("utf-8"))
        except (OSError, ValueError) as error:
            raise Refused(f"{what} {path} unreadable: {type(error).__name__}: {error}")

    def optional_json(self, path: Path) -> Any:
        return self.json(path, "file") if path.is_file() else None


class Chain:
    """The read-only view of one record_runs.py chain directory."""

    def __init__(self, directory: Path, inputs: Inputs) -> None:
        if not (directory / "steps").is_dir():
            raise Refused(f"{directory} is not a record_runs.py chain directory (no steps/)")
        self.dir, self.logs, self.inputs = directory, directory.parent, inputs
        self.config = inputs.optional_json(directory / "config.json") or {}
        self.run_list_doc = inputs.optional_json(directory / "run-list.json")
        self.status = inputs.optional_json(directory / "chain-status.json") or {}
        self.manifest = inputs.optional_json(directory / "manifest.json")
        name = directory.name
        self.ts = self.config.get("ts") or (name[len("record-runs-"):] if name.startswith("record-runs-") else None)
        source = (self.manifest or {}).get("run_list") or self.run_list_doc
        if not isinstance(source, dict) or not isinstance(source.get("runs"), list):
            raise Refused("neither manifest.json run_list nor run-list.json is readable: the run list is unknown")
        self.run_list = source
        self.profile_id = (self.manifest or {}).get("profile") or source.get("profile")
        if not isinstance(self.profile_id, str) or not self.profile_id:
            raise Refused("the chain's deployment profile id is unknown")

    def step(self, name: str) -> tuple[str, dict] | None:
        for state in ("done", "failed"):
            path = self.dir / "steps" / f"{name}.{state}.json"
            if path.is_file():
                return state, self.inputs.json(path, f"step record {name}")
        return None

    def done(self, name: str) -> dict | None:
        got = self.step(name)
        return got[1].get("decision") if got and got[0] == "done" else None

    def levels(self) -> list[tuple[dict, int]]:
        out = []
        for run in self.run_list["runs"]:
            for level in run.get("levels") or []:
                out.append((run, int(level)))
        return out


# ---------------------------------------------------------------- the verification report
def verification_ok(report: Any) -> tuple[bool, str]:
    """record_runs.verification_verdict, restated: 11 selected, verdict pass, none failed."""
    if not isinstance(report, dict):
        return False, "verification report unreadable"
    selected, failed = report.get("selected_checks") or [], report.get("failed_checks") or []
    if len(selected) != EXPECTED_CHECKS:
        return False, f"{len(selected)} of {EXPECTED_CHECKS} checks selected (skipped: {report.get('skipped_checks')})"
    if report.get("verdict") != "pass" or failed:
        return False, f"verdict {report.get('verdict')!r}, failed checks {failed}"
    return True, f"{EXPECTED_CHECKS}/{EXPECTED_CHECKS} PASS"


def merged_facts(report: dict) -> tuple[dict[tuple[str, ...], Any], dict[tuple[str, ...], str]]:
    """Every observed leaf of every check, with the check that observed it; two checks may agree, never disagree."""
    facts: dict[tuple[str, ...], Any] = {}
    source: dict[tuple[str, ...], str] = {}
    for check in sorted(report.get("checks") or {}):
        entry = report["checks"][check] or {}
        for path, value in leaves(entry.get("facts") or {}):
            if not path:
                continue
            if path in facts and facts[path] != value:
                raise Refused(f"conflicting observations for {show(path)}: {facts[path]!r} ({source[path]}) vs "
                              f"{value!r} ({check})")
            facts.setdefault(path, value)
            source.setdefault(path, check)
    return facts, source


def non_placeholder_failures(report: dict, lock: dict) -> list[str]:
    """Bootstrap rule: every failure must read '<path>: base-lock says 'TODO-R0:...' with a placeholder at <path>."""
    bad = []
    for check in sorted(report.get("checks") or {}):
        entry = report["checks"][check] or {}
        if entry.get("verdict") == "pass":
            continue
        failures = entry.get("failures") or []
        if not failures:
            bad.append(f"{check}: verdict {entry.get('verdict')!r} without a failure list")
        for failure in failures:
            head, sep, tail = str(failure).partition(SAYS)
            ok = False
            if sep and (tail.startswith("'" + PLACEHOLDER) or tail.startswith('"' + PLACEHOLDER)):
                try:
                    ok = is_placeholder(lookup(lock, tuple(head.split(" > "))))
                except KeyError:
                    ok = False
            if not ok:
                bad.append(f"{check}: {failure}")
    return bad


# ---------------------------------------------------------------- the plan
def plan_lock(lock: dict, facts: dict, source: dict, profile_id: str, report_path: str) -> dict:
    fills, unmapped, others, differences = [], [], [], []
    for path, value in leaves(lock):
        if not path or path[0] in NOT_COMPARED:
            continue
        if is_placeholder(value):
            if other_profile(path, profile_id):
                others.append(list(path))
            elif path in facts and not is_placeholder(facts[path]):
                fills.append({"field": list(path), "value": facts[path],
                              "source": f"{report_path} checks.{source[path]}.facts", "placeholder": value})
            else:
                unmapped.append(list(path))
        elif path in facts and not other_profile(path, profile_id) and not values_equal(path, value, facts[path]):
            differences.append(f"{show(path)}: record {value!r}, observed {facts[path]!r} ({source[path]})")
    return {"fills": fills, "unmapped": unmapped, "other_profiles": others, "differences": differences}


def fmt(value: Any, digits: int = 1, thousands: bool = False) -> str:
    if value is None or isinstance(value, bool) or not isinstance(value, (int, float)):
        return "-"
    return f"{value:,.{digits}f}" if thousands else f"{value:.{digits}f}"


def pick(doc: Any, *keys: str) -> Any:
    for key in keys:
        if not isinstance(doc, dict):
            return None
        doc = doc.get(key)
    return doc


def run_label(run: dict) -> str:
    label = str(run["id"])
    extra = []
    if run.get("min_tokens"):
        extra.append(f"worst case `--min-tokens {run['min_tokens']}`")
    sweep = run.get("sweep") or {}
    if "max_tokens" in sweep:
        extra.append(f"max_tokens {sweep['max_tokens']}")
    if "thinking_budget" in sweep:
        extra.append(f"budget {sweep['thinking_budget']}")
    return label + (f" ({', '.join(extra)})" if extra else "")


def s8_rows(chain: Chain) -> tuple[list[list[str]], list[str]]:
    """One table row per (run, level) in run-list order; refuses a level with no step record."""
    rows, missing = [], []
    for run, level in chain.levels():
        step_id = f"{run['id']}-L{level}"
        got = chain.step(step_id)
        if got is None:
            missing.append(step_id)
            continue
        state, record = got
        blank = ["-"] * 13  # cells of a level without a measured row
        if state == "failed":
            reasons = record.get("failing_reasons") or [record.get("reason") or "failed"]
            rows.append([run_label(run), str(level), "-", "-"] + blank + ["FAIL: " + "; ".join(map(str, reasons))])
            continue
        decision = record.get("decision") or {}
        if "row" not in decision:
            why = decision.get("skipped") or "no row recorded"
            rows.append([run_label(run), str(level), "-", "-"] + blank + [f"not run: {why}"])
            continue
        row = decision["row"]
        report = chain.logs / str(row.get("report", ""))
        if row.get("report") and report.is_file():
            actual = sha256_bytes(chain.inputs.raw(report))
            if actual != row.get("report_sha256"):
                raise Refused(f"{step_id}: level report {report} sha256 {actual} differs from the row's "
                              f"{row.get('report_sha256')}")
        inst = row.get("instances") or len(row.get("per_instance") or []) or 1
        wall, ok, host = row.get("wall_s"), row.get("ok"), row.get("host_output_tok_s")
        cpm = ok / wall * 60 / inst if isinstance(ok, (int, float)) and isinstance(wall, (int, float)) and wall else None
        per = row.get("per_instance") or []
        agreement = pick(row, "greedy_probe", "sequential_before_vs_after")
        if isinstance(agreement, list) and agreement:
            probe = ", ".join(f"{c.get('byte_identical')}/{c.get('requests')}" if isinstance(c, dict) else "n/a"
                              for c in agreement)
        else:
            probe = "not recorded (a probe failed)"
        verdict = "PASS" if row.get("passes") else "FAIL: " + "; ".join(map(str, row.get("failing_reasons") or []))
        if row.get("worst_case"):
            verdict += f" (admissible: {'yes' if row.get('worst_case_admissible') else 'no'})"
        lat = row.get("latency_s") or {}
        rows.append([
            run_label(run), str(level), str(level * inst),
            f"{row.get('passes_requested', run.get('passes', 1))} pass(es), {ok}/{row.get('requests')} ok",
            f"`{row.get('report')}`", f"`{row.get('report_sha256')}`", fmt(host, 1, True),
            fmt(host / inst if isinstance(host, (int, float)) else None, 1, True), fmt(cpm, 2),
            f"{fmt(pick(row, 'e2e_tok_s', 'p50'), 2)} / {fmt(pick(row, 'e2e_tok_s', 'p10'), 2)}",
            f"{fmt(lat.get('p50'), 1)} / {fmt(lat.get('p95'), 1)} / {fmt(lat.get('max'), 1)}",
            fmt(pick(row, "ttft_s", "p95"), 2),
            "/".join(fmt(p.get("preemptions_delta"), 0) for p in per) or fmt(row.get("preemptions_delta"), 0),
            "/".join(fmt(p.get("kv_peak") * 100 if isinstance(p.get("kv_peak"), (int, float)) else None, 1)
                     for p in per) + (" %" if per else "-"),
            fmt(row.get("min_hbm_free_mib_per_card"), 0), fmt(row.get("num_requests_waiting_peak"), 0), probe, verdict])
    return rows, missing


HEADER = ["run", "level / inst", "host conc.", "requests", "report (LOGS/)", "sha256", "host out tok/s",
          "per-inst tok/s", "contacts/min/inst", "e2e p50 / p10", "latency p50 / p95 / max s", "TTFT p95 s",
          "preemptions per inst", "KV peak per inst", "min HBM free MiB", "waiting peak",
          "probe before / after (sequential agreement)", "verdict"]


def render_block(chain: Chain, rows: list[list[str]], facts: dict, verification: dict) -> str:
    m = chain.manifest or {}
    seeds = sorted({str(v) for v in (m.get("server_seeds") or {}).values()})
    smi = lambda d: ", ".join(f"{k}: {d[k]}" for k in sorted(d, key=lambda x: int(x))) if isinstance(d, dict) else "-"
    lines = [BEGIN, "",
             f"Recorded runs of chain `{chain.dir.name}` (filled from the chain's step records; the cell values are the "
             f"rows `record_runs.py` wrote, per-inst tok/s = host / instances, contacts/min/inst = ok / wall x 60 / "
             f"instances).", "",
             "| " + " | ".join(HEADER) + " |", "|" + "---|" * len(HEADER)]
    lines += ["| " + " | ".join(cell.replace("|", "/") for cell in row) + " |" for row in rows]
    lines += ["", "Recorded-run manifest facts:", "",
              f"- profile `{m.get('profile', chain.profile_id)}`, profile file sha256 `{m.get('profile_sha256')}`, "
              f"ceiling {m.get('max_num_seqs_ceiling')}, admitted level of the run list {m.get('admitted_level')}; "
              f"git head `{m.get('git_head')}`; host `{m.get('host')}`.",
              f"- runtime receipt `{m.get('receipt')}`, `protocol_sha256` "
              f"`{facts.get(('protocol', 'protocol_sha256'), '-')}`.",
              f"- base verification `{verification['report']}`, sha256 `{verification['sha256']}`, "
              f"{verification['verdict']}.",
              f"- client seed {m.get('client_seed')}, client decoding seed default "
              f"{m.get('client_decoding_seed_default')}, server `--seed` {', '.join(seeds) or '-'}; greedy probe decoding "
              f"seed {pick(m, 'probe', 'decoding_seed')}, bodies sha256 `{pick(m, 'probe', 'bodies_sha256')}`, "
              f"{pick(m, 'probe', 'send')} send (recorded, never gated).",
              f"- `npu-smi` HBM used MiB per card before: {smi(m.get('npu_smi_before'))}; after: "
              f"{smi(m.get('npu_smi_after'))}.", "", END]
    return "\n".join(lines) + "\n"


def apply_block(text: str, block: str) -> str:
    if BEGIN in text or END in text:
        start, end = text.find(BEGIN), text.find(END)
        if start < 0 or end < start:
            raise Refused("the speed baseline holds an unbalanced generated block")
        current = text[start:end + len(END)] + "\n"
        if current != block:
            raise Refused("the speed baseline already holds a DIFFERENT generated block; refusing to overwrite it")
        return text
    if S8_SECTION not in text:
        raise Refused(f"the speed baseline has no {S8_SECTION!r} section")
    section = text.index(S8_SECTION)
    anchor = text.find(S8_ANCHOR, section)
    if anchor < 0 or text.rfind("\n", 0, anchor) + 1 != anchor:
        raise Refused(f"the speed baseline has no line starting {S8_ANCHOR!r} in section 1")
    return text[:anchor] + block + "\n" + text[anchor:]


# ---------------------------------------------------------------- driver
def build(args: argparse.Namespace) -> dict:
    inputs = Inputs()
    chain_dir = Path(args.chain_dir).resolve()
    chain = Chain(chain_dir, inputs)
    if chain.status.get("state") == "running":
        raise Refused(f"chain {chain_dir.name} is still running (chain-status.json state 'running')")
    required = BOOTSTRAP_STEPS if args.bootstrap else R0_STEPS
    missing = [name for name in required if chain.done(name) is None]
    if missing:
        raise Refused(f"required R0 step(s) not done: {missing}")
    lock_path, s8_path = Path(args.base_lock).resolve(), Path(args.speed_baseline).resolve()
    lock_raw = inputs.raw(lock_path)
    try:
        lock = json.loads(lock_raw.decode("utf-8"))
    except ValueError as error:
        raise Refused(f"base-lock {lock_path} is not JSON: {error}")
    if not isinstance(lock, dict) or lock.get("schema") != LOCK_SCHEMA:
        raise Refused(f"base-lock schema must be {LOCK_SCHEMA!r}")
    if canonical(lock).encode("utf-8") != lock_raw:
        raise Refused("base-lock is not in canonical form (indent 2, sorted keys, ASCII, final newline); a fill would "
                      "rewrite more than the placeholders")
    lock_sha = sha256_bytes(lock_raw)

    verify = chain.done("verify-base")
    if verify is not None:
        report_path = Path(verify.get("report") or "")
        recorded_sha, verdict_text = verify.get("sha256"), verify.get("verdict")
    elif args.bootstrap:  # the failed step does not record its report; the path is the driver's fixed name
        report_path = chain.logs / f"base-verification-{chain.profile_id}-rec-{chain.ts}.json"
        recorded_sha, verdict_text = None, None
    else:
        raise Refused("verify-base is not done")
    report_raw = inputs.raw(report_path) if report_path.is_file() else None
    if report_raw is None:
        raise Refused(f"verification report {report_path} unreadable")
    if recorded_sha is not None and sha256_bytes(report_raw) != recorded_sha:
        raise Refused(f"verification report sha256 {sha256_bytes(report_raw)} differs from the verify-base step's "
                      f"{recorded_sha}")
    report = json.loads(report_raw.decode("utf-8"))
    ok, why = verification_ok(report)
    if not args.bootstrap and (not ok or verdict_text != f"{EXPECTED_CHECKS}/{EXPECTED_CHECKS} PASS"):
        raise Refused(f"verify-base is not {EXPECTED_CHECKS}/{EXPECTED_CHECKS} PASS: {why} (step verdict {verdict_text!r})")
    if (report.get("inputs") or {}).get("profile_id") not in (None, chain.profile_id):
        raise Refused(f"the verification ran on profile {report['inputs']['profile_id']!r}, the chain on "
                      f"{chain.profile_id!r}")
    if args.bootstrap:
        if len(report.get("selected_checks") or []) != EXPECTED_CHECKS:
            raise Refused(f"bootstrap: {why}")
        if (report.get("inputs") or {}).get("base_lock_sha256") != lock_sha:
            raise Refused("bootstrap: the verification did not run against the record as it is now "
                          f"(report base_lock_sha256 {(report.get('inputs') or {}).get('base_lock_sha256')}, record {lock_sha})")
        bad = non_placeholder_failures(report, lock)
        if bad:
            raise Refused("bootstrap: the verification has failures that are not placeholder mismatches: " + " | ".join(bad))
        why = f"bootstrap: {why}; every failure is a TODO-R0 placeholder mismatch"

    facts, source = merged_facts(report)
    plan = plan_lock(lock, facts, source, chain.profile_id, str(report_path))
    if plan["differences"]:
        raise Refused("observed values differ from non-placeholder leaves (never overwritten): " +
                      " | ".join(plan["differences"]))
    receipt_step = chain.done("receipt") or {}
    observed_receipt = facts.get(("receipt", "path"))
    if observed_receipt is not None and receipt_step.get("receipt") not in (None, observed_receipt):
        raise Refused(f"receipt path observed {observed_receipt!r} is not the receipt step's {receipt_step.get('receipt')!r}")
    notes = []
    runtime = Path(str(receipt_step.get("receipt") or ""))
    proto = facts.get(("protocol", "protocol_sha256"))
    if runtime.is_file():
        doc = inputs.json(runtime, "runtime receipt")
        if proto is not None and doc.get("protocol_sha256") != proto:
            raise Refused(f"protocol_sha256 observed {proto} is not the runtime receipt's {doc.get('protocol_sha256')}")
    else:
        notes.append(f"runtime receipt {runtime} not readable here; protocol_sha256 not cross-checked against it")

    new_lock = json.loads(json.dumps(lock))
    for fill in plan["fills"]:
        assign(new_lock, tuple(fill["field"]), fill["value"])
    new_lock_text = canonical(new_lock)

    s8_raw = inputs.raw(s8_path)
    s8_text = s8_raw.decode("utf-8")
    block, rows = None, []
    if args.bootstrap:
        new_s8 = s8_text
        notes.append("bootstrap: the S8 table is not filled; re-run verify-base (record_runs.py --resume) to 11/11 first")
    else:
        rows, missing_levels = s8_rows(chain)
        if missing_levels:
            raise Refused(f"run level(s) with no step record (chain unfinished or stopped): {missing_levels}")
        block = render_block(chain, rows, facts, {"report": str(report_path), "sha256": sha256_bytes(report_raw),
                                                   "verdict": why})
        new_s8 = apply_block(s8_text, block)
    return {"chain": chain, "inputs": inputs, "lock_path": lock_path, "s8_path": s8_path, "lock_raw": lock_raw,
            "new_lock_text": new_lock_text, "s8_raw": s8_raw, "new_s8": new_s8, "plan": plan, "block": block,
            "rows": rows, "verification": {"report": str(report_path), "sha256": sha256_bytes(report_raw),
                                           "verdict": why}, "notes": notes}


def write_atomic(path: Path, text: str) -> None:
    fd, tmp = tempfile.mkstemp(dir=str(path.parent), prefix=f".{path.name}.")
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="") as handle:
            handle.write(text)
        os.chmod(tmp, 0o666 & ~_umask())
        os.replace(tmp, path)
    except BaseException:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise


def _umask() -> int:
    mask = os.umask(0)
    os.umask(mask)
    return mask


def receipt_doc(result: dict, args: argparse.Namespace) -> dict:
    plan, chain = result["plan"], result["chain"]
    return {
        "schema": RECEIPT_SCHEMA, "mode": "bootstrap" if args.bootstrap else "record",
        "chain_dir": str(chain.dir), "chain": chain.dir.name, "profile": chain.profile_id,
        "script": str(Path(__file__).resolve()), "script_sha256": sha256_bytes(Path(__file__).resolve().read_bytes()),
        "verification": result["verification"],
        "inputs": dict(sorted(result["inputs"].hashes.items())),
        "outputs": {
            str(result["lock_path"]): {"before": sha256_bytes(result["lock_raw"]),
                                       "after": sha256_bytes(result["new_lock_text"].encode("utf-8"))},
            str(result["s8_path"]): {"before": sha256_bytes(result["s8_raw"]),
                                     "after": sha256_bytes(result["new_s8"].encode("utf-8"))}},
        "filled_fields": [{"field": f["field"], "source": f["source"]} for f in plan["fills"]],
        "s8_rows": len(result["rows"]), "s8_block_written": result["block"] is not None,
        "placeholders_left_other_profiles": plan["other_profiles"],
        "placeholders_left_unmapped": plan["unmapped"],
        "notes": result["notes"],
        "authority": "Port engineering record only; grants no contact authority, readiness flip or exposure entry.",
    }


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--chain-dir", required=True, help="record_runs.py chain directory <logs>/record-runs-<ts>")
    p.add_argument("--base-lock", default=str(DEFAULT_LOCK))
    p.add_argument("--speed-baseline", default=str(DEFAULT_S8))
    p.add_argument("--receipt-out", help="fill receipt path (default <chain-dir>/fill-receipt.json; never overwritten)")
    p.add_argument("--bootstrap", action="store_true", help="first R0 against a skeleton record (see the docstring)")
    p.add_argument("--dry-run", action="store_true", help="print the field map and the S8 block; write nothing")
    args = p.parse_args(argv)
    try:
        result = build(args)
        receipt_path = Path(args.receipt_out or Path(args.chain_dir) / "fill-receipt.json")
        if not args.dry_run and receipt_path.exists():
            raise Refused(f"{receipt_path} exists; a fill already ran (pass --receipt-out to record another one)")
    except Refused as error:
        print(f"refused: {error}", file=sys.stderr)
        return 2
    plan = result["plan"]
    if args.dry_run:
        print(json.dumps({"mode": "bootstrap" if args.bootstrap else "record", "chain": result["chain"].dir.name,
                          "profile": result["chain"].profile_id, "verification": result["verification"],
                          "field_map": [{"field": show(tuple(f["field"])), "value": f["value"], "source": f["source"]}
                                        for f in plan["fills"]],
                          "unmapped": [show(tuple(x)) for x in plan["unmapped"]],
                          "other_profiles": len(plan["other_profiles"]), "notes": result["notes"]},
                         indent=1, sort_keys=True))
        if result["block"]:
            print(result["block"], end="")
        return 0
    if result["new_lock_text"].encode("utf-8") != result["lock_raw"]:
        write_atomic(result["lock_path"], result["new_lock_text"])
    if result["new_s8"].encode("utf-8") != result["s8_raw"]:
        write_atomic(result["s8_path"], result["new_s8"])
    write_atomic(receipt_path, json.dumps(receipt_doc(result, args), indent=1, sort_keys=True) + "\n")
    print(f"filled {len(plan['fills'])} lock field(s), {len(result['rows'])} S8 row(s); "
          f"{len(plan['unmapped'])} unmapped, {len(plan['other_profiles'])} left for other profiles; receipt {receipt_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
