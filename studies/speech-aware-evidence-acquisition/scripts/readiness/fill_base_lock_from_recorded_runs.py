#!/usr/bin/env python3
"""Fill the base-lock record's ``TODO-R0:`` leaves and the S8 recorded table from one ``record_runs.py`` chain directory.

    python scripts/readiness/fill_base_lock_from_recorded_runs.py --chain-dir <logs>/record-runs-<ts> [--dry-run]
        [--base-lock docs/readiness/.../base-lock-v1.json] [--speed-baseline docs/results/...-speed-baseline-v1.md]
        [--receipt-out PATH] [--bootstrap]

Model-free and deterministic: it reads files only (no host, docker, HTTP or clock), and the same inputs give the same
outputs byte for byte. Standard library only.

Inputs, all produced by ``work/scripts/record_runs.py`` (layout ``<logs>/record-runs-<ts>/`` with ``config.json``,
``run-list.json``, ``chain-status.json``, ``manifest.json``, ``steps/<step>.{done,failed}.json``; reports beside the chain
directory in ``<logs>``):

* lock leaves come from the R0 verification report (``steps/verify-base.done.json`` -> ``decision.report``), whose
  ``checks.<check>.facts`` hold every OBSERVED leaf in the base-lock shape (``verify_engineering_base.py`` builds them
  from its claims, also when a check fails). A leaf is filled only if its current value is a string starting with
  ``TODO-R0:``; a non-placeholder leaf is NEVER written, and an observed value that differs from a non-placeholder leaf
  is a refusal (``kv_tokens`` and ``max_concurrency`` compare within 1 %, as the verifier does). Leaves under
  ``profiles.<id>`` are filled only for the chain's own profile; placeholders of other profiles are listed, not touched.
* S8 rows come from ``steps/<run>-L<level>.done.json`` -> ``decision.row`` (the same row ``record_runs.py`` writes to
  ``sweep-rec-...-L<level>.row.json``); manifest facts from ``manifest.json``. The table is written as ONE generated block
  between the markers below, inserted before the skeleton's branch tables; an existing block is replaced only if it is
  byte-identical (otherwise refused).

Refusals (exit 2, nothing written): a missing R0 step, ``verify-base`` not 11/11 PASS (11 checks selected, verdict
pass, none failed; the report's sha256 must equal the step's), a run level with no step record, a chain still running,
a level report whose sha256 differs from its row, conflicting observations, a record that is not canonical JSON.

``--bootstrap`` is the one exception to 11/11, for the first R0 against a skeleton record (every placeholder fails its
check closed, so a skeleton can never verify 11/11): it requires the R0 steps up to ``receipt``, a verification report
for the record AS IT IS NOW (``inputs.base_lock_sha256`` equal to the record's sha256) in which EVERY failure is a
placeholder mismatch ("<path>: base-lock says 'TODO-R0:..."), fills only lock leaves (no S8), and says so in the
receipt; the verification must then be repeated (``record_runs.py --resume`` re-runs ``verify-base``).

Every write is atomic; a ``fill-receipt.json`` (default ``<chain-dir>/fill-receipt.json``, never overwritten) records
the chain directory, the sha256 of every input and of both outputs before and after, and the list of filled fields.
``--dry-run`` prints the field map (field -> value -> source) and the planned S8 block, and writes nothing.
"""

