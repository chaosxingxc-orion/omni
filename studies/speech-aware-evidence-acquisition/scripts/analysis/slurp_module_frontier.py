def fmt(value: Any, places: int = 2) -> str:
    if value is None:
        return "--"
    if isinstance(value, float):
        return f"{value:.{places}f}"
    return str(value)


def ci(bounds: Sequence[float] | None) -> str:
    if not bounds:
        return "--"
    return f"[{bounds[0]:+.2f}, {bounds[1]:+.2f}]"


def report(collected: Mapping[str, Any], front: Mapping[str, Any]) -> str:
    rows = sorted(collected["rows"], key=lambda r: -float(r["official"]["arm_slu_pp"]))
    lines: list[str] = []
    add = lines.append

    add("## Table A1 -- the decided SLURP cells, absolute official numbers and cost")
    add("")
    add("Absolute official `slurp-slu-official-train` numbers on the shared 1,080-row "
        "TRAIN Fold A roster. This is the table the frontier is built on, because it is "
        "the only one whose numbers are comparable across cells.")
    add("")
    add("| Cell | Status | Official SLU | Official intent | GPU-h / 1,080 | Contacts / row "
        "| Prefilled tok / row | Token basis | Cost caveat |")
    add("| --- | --- | ---: | ---: | ---: | ---: | ---: | --- | --- |")
    for row in rows:
        kind = "measured" if row["cost"]["prefilled_tokens_kind"] == "verdict-measured" else "PROXY"
        note = row["cost"].get("note") or ""
        caveat = "resume attempt only (understates)" if "resume" in note else (
            "pinned from a verdict" if row["cost"]["basis"].startswith("PINNED") else (
                "the base's cost; the node adds none" if row["cost"]["zero_contact_module"] else "--"
            )
        )
        add("| {cell} | {status} | {slu} | {intent} | {gpu} | {contacts} | {pre} | {kind} | {cav} |".format(
            cell=row["cell_id"] + (" *(control)*" if row["is_control"] else ""),
            status=row["status"],
            slu=fmt(row["official"]["arm_slu_pp"]),
            intent=fmt(row["official"]["arm_intent_pp"]),
            gpu=fmt(row["cost"]["gpu_hours_per_1080"], 4),
            contacts=fmt(row["cost"]["contacts_per_row"], 3),
            pre=fmt(row["cost"]["prefilled_tokens_per_row"], 1),
            kind=kind,
            cav=caveat,
        ))
    add("")
    add("Cost caveats in full:")
    add("")
    for row in rows:
        note = row["cost"].get("note")
        if note:
            add(f"- **{row['cell_id']}**: {note}.")
    add("")

    add("## Table A2 -- each cell against ITS OWN comparator (never chained)")
    add("")
    add("| Cell | Comparator | Comparator family | SLU delta | SLU CI95 | Intent delta "
        "| Intent CI95 | Margins (h_SLU / h_intent) |")
    add("| --- | --- | --- | ---: | --- | ---: | --- | --- |")
    for row in rows:
        add("| {cell} | {cmp} | {fam} | {ds:+.2f} | {cs} | {di:+.2f} | {cint} | {m} |".format(
            cell=row["cell_id"],
            cmp=row["comparator_run_id"] or "--",
            fam=row["comparator_family"],
            ds=row["delta"]["slu_pp"],
            cs=ci(row["delta"]["slu_ci95_pp"]),
            di=row["delta"]["intent_pp"],
            cint=ci(row["delta"]["intent_ci95_pp"]),
            m=f"{row['margins_h_slu_pp']:.4f} / {row['margins_h_intent_pp']:.4f}",
        ))
    add("")

    for plane, title in (
        ("gpu_hours", "GPU hours per 1,080 rows"),
        ("prefilled_tokens", "prefilled tokens per row"),
    ):
        block = front["planes"][plane]
        add(f"## Table A3.{plane} -- the Pareto frontier against {title}")
        add("")
        add("Frontier (cheapest first): " + ", ".join(f"**{x}**" for x in block["frontier"]))
        knee_block = block["knee"]
        if knee_block.get("knee"):
            add("")
            add(f"Knee: **{knee_block['knee']}** "
                f"(scaled chord distance {knee_block['scaled_chord_distance']:.3f}). "
                f"{knee_block['definition']}.")
        add("")
        add("| Cell | Cost | Official SLU | On frontier? | Dominated by |")
        add("| --- | ---: | ---: | --- | --- |")
        for label, point in sorted(block["points"].items(), key=lambda kv: kv[1]["cost"]):
            on = "**yes**" if label in block["frontier"] else "no"
            dom = ", ".join(block["dominated"].get(label, [])) or "--"
            add(f"| {label} | {point['cost']:,.4f} | {point['official_slu_pp']:.2f} | {on} | {dom} |")
        add("")

    add("## Table A4 -- the frontier per scenario (GPU-hour plane)")
    add("")
    summary = front["per_scenario_summary"]
    add(f"Scenarios with a per-scenario table on every cell read: "
        f"{summary['scenarios_with_a_table']} of {len(SCENARIOS)}.")
    add("")
    add("| Scenario | Cells with a table | Frontier | Best cell | Best official SLU |")
    add("| --- | ---: | --- | --- | ---: |")
    for scenario in SCENARIOS:
        block = front["per_scenario"][scenario]
        if not block.get("available"):
            add(f"| {scenario} | 0 | -- | -- | -- |")
            continue
        add("| {s} | {n} | {f} | {b} | {v:.2f} |".format(
            s=scenario,
            n=block["cells_with_a_per_scenario_table"],
            f=", ".join(block["frontier"]),
            b=block["best_cell"],
            v=block["best_official_slu_pp"],
        ))
    add("")
    add("Frontier membership counts over the scenarios: " + ", ".join(
        f"{label} {count}" for label, count in summary["frontier_membership_counts"].items()
    ) + ".")
    add("")
    add("Never on any scenario's frontier: " + (
        ", ".join(summary["never_on_any_scenario_frontier"]) or "none"
    ) + ".")
    return "\n".join(lines) + "\n"


