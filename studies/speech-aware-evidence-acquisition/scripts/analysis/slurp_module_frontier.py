class FrontierError(RuntimeError):
    """A sealed input is missing or does not have the shape this read needs."""


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def read_json(path: Path) -> Any:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except OSError as error:
        raise FrontierError(f"cannot read {path}: {error}") from error


def dig(document: Any, path: Sequence[str], label: str) -> Any:
    node = document
    for key in path:
        if not isinstance(node, Mapping) or key not in node:
            raise FrontierError(f"{label}: no key {key!r} at {'/'.join(path)}")
        node = node[key]
    return node


def attempt_dir(data_root: Path, arm: Arm) -> Path | None:
    if arm.run_id is None or arm.attempt_id is None:
        return None
    return data_root / "runs" / arm.run_id / arm.attempt_id


def read_cost(data_root: Path, arm: Arm) -> dict[str, Any]:
    """GPU hours, contacts and client prompt tokens for one sealed arm.

    GPU hours are the serving monitor's own ``active_seconds`` divided by
    3,600 -- the definition every SLURP verdict's cost block uses. Contacts
    and prompt tokens are the seal stage's own cost block, which is the same
    object the generation manifest's ``cost`` carries.
    """

    directory = attempt_dir(data_root, arm)
    receipts = directory / "flight-receipts.json" if directory is not None else None
    if receipts is None or not receipts.is_file():
        if arm.pinned_cost is None:
            raise FrontierError(
                f"arm {arm.key!r} has no flight receipt and no pinned cost transcription"
            )
        out = dict(arm.pinned_cost)
        out["basis"] = "PINNED transcription (no sealed flight receipt for this attempt)"
        out["note"] = arm.note
        return out

    document = read_json(receipts)
    seal = dig(document, ("stages", "seal"), f"{arm.key} flight receipts")
    monitor = dig(document, ("stages", "seal", "serving_monitor_summary"),
                  f"{arm.key} flight receipts")
    run_phases = dig(document, ("stages", "run_phases"), f"{arm.key} flight receipts")
    cost = dig(seal, ("cost",), f"{arm.key} seal stage")
    active = float(monitor["active_seconds"])
    return {
        "basis": "sealed flight-receipts.json",
        "source": str(receipts),
        "source_sha256": sha256_file(receipts),
        "run_id": arm.run_id,
        "attempt_id": arm.attempt_id,
        "gpu_hours": active / 3600.0,
        "monitor_active_seconds": active,
        "contacts": int(cost["calls_used"]),
        "prompt_tokens_total": int(cost["prompt_tokens_total"]),
        "completion_tokens_total": int(cost["completion_tokens_total"]),
        "audio_seconds_used": float(cost["audio_seconds_used"]),
        "tool_calls": int(cost["tool_calls"]),
        "wall_seconds": float(run_phases["wall_seconds"]),
        "slot_occupancy": float(run_phases["slot_occupancy"]),
        "mean_utilisation_percent": float(monitor["mean_utilization_percent"]),
        "parked_fraction": float(monitor["parked_fraction"]),
        "note": arm.note,
    }


def read_official(data_root: Path, arm: Arm) -> dict[str, Any] | None:
    """The arm's own sealed official aggregate, read for the self-check."""

    directory = attempt_dir(data_root, arm)
    if directory is None:
        return None
    scores = directory / f"{arm.run_id}.scores.json"
    if not scores.is_file():
        return None
    document = read_json(scores)
    aggregate = dig(document, ("slurp-slu-official-train", "aggregate", "official"),
                    f"{arm.key} scores.json")
    return {
        "source": str(scores),
        "slu_f1_pp": 100.0 * float(aggregate["slu_f1"]),
        "intent_pp": 100.0 * float(aggregate["intent_accuracy"]),
        "scenario_pp": 100.0 * float(aggregate["scenario_accuracy"]),
        "action_pp": 100.0 * float(aggregate["action_accuracy"]),
        "span_f1_pp": 100.0 * float(aggregate["span_f1"]),
    }


def interval(block: Mapping[str, Any], resampling: str) -> dict[str, Any]:
    entry = block.get(resampling)
    if not isinstance(entry, Mapping):
        raise FrontierError(f"no {resampling} interval in this contrast block")
    low, high = entry["ci95_pp"]
    # The earliest paired reads (cells B0 and B0r) wrote the endpoints without
    # the derived half-width; it is recomputed here rather than required.
    half = entry.get("ci95_half_width_pp")
    if half is None:
        half = (float(high) - float(low)) / 2.0
    return {
        "point_pp": float(entry.get("point_estimate_pp", (float(low) + float(high)) / 2.0)),
        "ci95_pp": [float(low), float(high)],
        "ci95_half_width_pp": float(half),
        "ci95_half_width_basis": "as written" if entry.get("ci95_half_width_pp") is not None
        else "recomputed as (upper - lower) / 2 (this driver wrote no half-width)",
        "resampling": entry.get("resampling"),
        "seed": entry.get("seed"),
        "n_replicates": entry.get("n_replicates"),
    }


def read_contrast(
    data_root: Path, cell: CellSpec, contrast_key: str
) -> dict[str, Any]:
    """One paired contrast, from the sealed paired read the verdict named."""

    path = data_root / "analysis" / cell.analysis_dir / "score-contrasts.json"
    if not path.is_file():
        raise FrontierError(f"cell {cell.cell_id}: no score-contrasts.json at {path}")
    document = read_json(path)
    comparisons = dig(document, cell.comparisons_path, f"cell {cell.cell_id}")
    if contrast_key not in comparisons:
        raise FrontierError(
            f"cell {cell.cell_id}: no contrast {contrast_key!r} "
            f"(available: {sorted(comparisons)})"
        )
    block = comparisons[contrast_key]
    slu = dig(block, ("pooled_micro", "slu_f1_micro"), f"cell {cell.cell_id}")
    intent = dig(block, ("per_row", "scenario_action_exact"), f"cell {cell.cell_id}")
    span = block.get("pooled_micro", {}).get("span_f1_micro")

    # Read the interval this cell's OWN registered estimator produced. Cell
    # B8b-anchor's registered estimator is the paired per-row bootstrap at seed
    # 20260919 and its driver names that block ``registered``, carrying the
    # speaker-clustered one as ``speaker_clustered_unregistered``; every other
    # driver names the speaker-clustered block ``speaker_clustered``.
    preferred = next(
        (name for name in ("speaker_clustered", "registered", "scenario_stratified")
         if name in slu),
        None,
    )
    if preferred is None:
        raise FrontierError(
            f"cell {cell.cell_id}: no known interval block "
            f"(available: {sorted(k for k in slu if isinstance(slu[k], Mapping))})"
        )

    out: dict[str, Any] = {
        "contrast_key": contrast_key,
        "source": str(path),
        "source_sha256": sha256_file(path),
        "json_pointer": "/".join(cell.comparisons_path + (contrast_key,)),
        "definition": block.get("contrast"),
        "row_counts": block.get("row_counts"),
        "slu": {
            "left_pct": float(slu["left_pct"]),
            "right_pct": float(slu["right_pct"]),
            "delta_pp": float(slu["delta_pp"]),
            "equal_scenario_delta_pp": slu.get("equal_scenario_delta_pp"),
            "interval": interval(slu, preferred),
        },
        "intent": {
            "left_pct": float(intent["left_pct"]),
            "right_pct": float(intent["right_pct"]),
            "delta_pp": float(intent["delta_pp"]),
            "equal_scenario_delta_pp": intent.get("equal_scenario_delta_pp"),
            "saves": intent.get("saves"),
            "harms": intent.get("harms"),
            "ties": intent.get("ties"),
            "sign_test_p": intent.get("sign_test_p"),
            "interval": interval(intent, preferred),
        },
        "per_scenario": {
            "slu": slu.get("per_scenario"),
            "intent": intent.get("per_scenario"),
        },
    }
    if isinstance(span, Mapping):
        out["span_f1"] = {
            "left_pct": float(span["left_pct"]),
            "right_pct": float(span["right_pct"]),
            "delta_pp": float(span["delta_pp"]),
        }
    return out


def cross_check_per_scenario(
    data_root: Path, cell: CellSpec, contrast_key: str, embedded: Mapping[str, Any] | None
) -> dict[str, Any]:
    """Verify the embedded per-scenario table against ``per-scenario-tables.json``.

    Both files are written by the same sealed driver; this check is what makes
    it safe to read the embedded copy uniformly across cells whose separate
    per-scenario file has a different top-level shape (or does not exist).
    """

    path = data_root / "analysis" / cell.analysis_dir / "per-scenario-tables.json"
    if not path.is_file():
        return {"checked": False, "reason": f"no per-scenario-tables.json under {cell.analysis_dir}"}
    if not isinstance(embedded, Mapping):
        return {"checked": False, "reason": "the contrast carries no embedded per-scenario table"}
    document = read_json(path)
    found: Mapping[str, Any] | None = None
    stack: list[Any] = [document]
    while stack:
        node = stack.pop()
        if isinstance(node, Mapping):
            candidate = node.get("pooled_slu_f1_per_scenario")
            if isinstance(candidate, Mapping) and set(candidate) >= set(SCENARIOS):
                parent_keys = set(node)
                if contrast_key in parent_keys or found is None:
                    found = candidate
            for key, value in node.items():
                if key == contrast_key and isinstance(value, Mapping):
                    inner = value.get("pooled_slu_f1_per_scenario")
                    if isinstance(inner, Mapping):
                        found = inner
                        stack = []
                        break
                stack.append(value)
        elif isinstance(node, list):
            stack.extend(node)
    if found is None:
        return {"checked": False, "reason": "no matching pooled per-scenario block in the file"}
    worst = 0.0
    for scenario in SCENARIOS:
        a = embedded.get(scenario, {}).get("right_pct")
        b = found.get(scenario, {}).get("right_pct")
        if a is None or b is None:
            return {"checked": False, "reason": f"scenario {scenario} missing on one side"}
        worst = max(worst, abs(float(a) - float(b)))
    return {
        "checked": True,
        "source": str(path),
        "source_sha256": sha256_file(path),
        "max_abs_difference_pp": worst,
        "agrees_1e-9": worst <= 1e-9,
    }


