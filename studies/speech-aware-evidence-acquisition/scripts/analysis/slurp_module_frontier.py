def pareto(points: Sequence[tuple[str, float, float]]) -> tuple[list[str], dict[str, list[str]]]:
    """Maximise effect, minimise cost.

    ``points`` are ``(label, cost, effect)``. A point is DOMINATED when another
    point is at least as good on both axes and strictly better on one.
    """

    frontier: list[str] = []
    dominated_by: dict[str, list[str]] = {}
    for label, cost, effect in points:
        dominators = [
            other
            for other, other_cost, other_effect in points
            if other != label
            and other_cost <= cost
            and other_effect >= effect
            and (other_cost < cost or other_effect > effect)
        ]
        if dominators:
            dominated_by[label] = sorted(dominators)
        else:
            frontier.append(label)
    frontier.sort(key=lambda label: next(c for l, c, _ in points if l == label))
    return frontier, dominated_by


def knee(points: Mapping[str, tuple[float, float]], frontier: Sequence[str]) -> dict[str, Any]:
    """The frontier's elbow: the frontier point farthest, after min-max scaling
    of both axes, from the chord joining the cheapest and the most effective
    frontier points. Stated as a formula so the choice is not a judgement."""

    if len(frontier) < 3:
        return {"knee": None, "reason": "a frontier of fewer than three points has no elbow"}
    costs = [points[label][0] for label in frontier]
    effects = [points[label][1] for label in frontier]
    c_lo, c_hi = min(costs), max(costs)
    e_lo, e_hi = min(effects), max(effects)
    if c_hi == c_lo or e_hi == e_lo:
        return {"knee": None, "reason": "a degenerate axis has no elbow"}

    def scale(label: str) -> tuple[float, float]:
        cost, effect = points[label]
        return ((cost - c_lo) / (c_hi - c_lo), (effect - e_lo) / (e_hi - e_lo))

    first = scale(frontier[0])
    last = scale(frontier[-1])
    dx, dy = last[0] - first[0], last[1] - first[1]
    norm = (dx * dx + dy * dy) ** 0.5
    best_label, best_distance = None, -1.0
    distances: dict[str, float] = {}
    for label in frontier:
        x, y = scale(label)
        distance = abs(dy * (x - first[0]) - dx * (y - first[1])) / norm
        distances[label] = distance
        if distance > best_distance:
            best_label, best_distance = label, distance
    return {
        "knee": best_label,
        "scaled_chord_distance": best_distance,
        "all_distances": distances,
        "definition": "min-max scale both axes over the frontier, join the cheapest and "
                      "the most effective frontier points with a chord, and take the "
                      "frontier point of greatest perpendicular distance from it",
    }


def build_frontier(collected: Mapping[str, Any]) -> dict[str, Any]:
    rows = collected["rows"]
    by_cell = {row["cell_id"]: row for row in rows}

    out: dict[str, Any] = {
        "schema": SCHEMA,
        "stage": "frontier",
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "axes_note": "effect = the arm's ABSOLUTE official pooled SLU-F1 on the shared "
                     "1,080-row roster; the deltas are not chained because the cells do "
                     "not share a comparator",
        "planes": {},
    }

    for plane, cost_key, cost_label in (
        ("gpu_hours", "gpu_hours_per_1080", "GPU hours per 1,080 rows"),
        ("prefilled_tokens", "prefilled_tokens_per_row", "prefilled tokens per row"),
    ):
        points = [
            (row["cell_id"], float(row["cost"][cost_key]), float(row["official"]["arm_slu_pp"]))
            for row in rows
        ]
        lookup = {label: (cost, effect) for label, cost, effect in points}
        frontier, dominated = pareto(points)
        out["planes"][plane] = {
            "cost_axis": cost_label,
            "points": {
                label: {
                    "cost": cost,
                    "official_slu_pp": effect,
                    "official_intent_pp": by_cell[label]["official"]["arm_intent_pp"],
                    "is_control": by_cell[label]["is_control"],
                    "cost_kind": by_cell[label]["cost"].get("prefilled_tokens_kind")
                    if plane == "prefilled_tokens" else by_cell[label]["cost"]["basis"],
                }
                for label, cost, effect in points
            },
            "frontier": frontier,
            "dominated": dominated,
            "knee": knee(lookup, frontier),
            "max_efficiency": max(
                ((label, effect / cost) for label, cost, effect in points if cost > 0),
                key=lambda pair: pair[1],
                default=(None, None),
            ),
        }

    # The intent plane, reported beside the primary.
    intent_points = [
        (row["cell_id"], float(row["cost"]["gpu_hours_per_1080"]),
         float(row["official"]["arm_intent_pp"]))
        for row in rows
    ]
    intent_frontier, intent_dominated = pareto(intent_points)
    out["planes"]["gpu_hours_intent"] = {
        "cost_axis": "GPU hours per 1,080 rows",
        "effect_axis": "absolute official intent (scenario+action) accuracy",
        "frontier": intent_frontier,
        "dominated": intent_dominated,
    }

    # Per scenario, on the GPU-hour plane.
    per_scenario: dict[str, Any] = {}
    for scenario in SCENARIOS:
        points = []
        for row in rows:
            block = (row.get("per_scenario") or {}).get("slu") or {}
            entry = block.get(scenario)
            if not isinstance(entry, Mapping) or entry.get("right_pct") is None:
                continue
            points.append((row["cell_id"], float(row["cost"]["gpu_hours_per_1080"]),
                           float(entry["right_pct"])))
        if not points:
            per_scenario[scenario] = {"available": False}
            continue
        frontier, dominated = pareto(points)
        per_scenario[scenario] = {
            "available": True,
            "cells_with_a_per_scenario_table": len(points),
            "frontier": frontier,
            "dominated": sorted(dominated),
            "best_cell": max(points, key=lambda p: p[2])[0],
            "best_official_slu_pp": max(points, key=lambda p: p[2])[2],
        }
    out["per_scenario"] = per_scenario

    pooled_frontier = set(out["planes"]["gpu_hours"]["frontier"])
    membership: dict[str, int] = {}
    scenario_count = 0
    for scenario, block in per_scenario.items():
        if not block.get("available"):
            continue
        scenario_count += 1
        for label in block["frontier"]:
            membership[label] = membership.get(label, 0) + 1
    out["per_scenario_summary"] = {
        "scenarios_with_a_table": scenario_count,
        "frontier_membership_counts": dict(sorted(
            membership.items(), key=lambda kv: (-kv[1], kv[0])
        )),
        "pooled_frontier": sorted(pooled_frontier),
        "always_on_the_frontier": sorted(
            label for label, count in membership.items() if count == scenario_count
        ),
        "never_on_any_scenario_frontier": sorted(
            row["cell_id"] for row in rows if membership.get(row["cell_id"], 0) == 0
        ),
    }
    return out


