def self_check(data_root: Path) -> int:
    failures = 0
    for case in SELF_CHECK:
        arm = ARMS[case["arm"]]
        if case["kind"] == "gpu_hours":
            got = float(read_cost(data_root, arm)["gpu_hours"])
        elif case["kind"] == "official_slu_pp":
            official = read_official(data_root, arm)
            if official is None:
                print(f"SELF-CHECK FAIL {case['name']}: no sealed scores.json")
                failures += 1
                continue
            got = float(official["slu_f1_pp"])
        else:  # pragma: no cover - the table is closed
            raise FrontierError(f"unknown self-check kind {case['kind']!r}")
        delta = abs(got - float(case["expected"]))
        ok = delta <= float(case["tolerance"])
        print(f"SELF-CHECK {'PASS' if ok else 'FAIL'} {case['name']}: "
              f"recomputed {got:.7f} against the pinned {case['expected']} "
              f"(|d| = {delta:.3e}, tolerance {case['tolerance']}); source {case['source']}")
        failures += 0 if ok else 1
    return failures


