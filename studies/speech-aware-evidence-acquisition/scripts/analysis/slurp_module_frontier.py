STAGES = ("collect", "frontier", "report", "all")


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="slurp_module_frontier.py",
        description=(
            "The effect-cost Pareto frontier of the decided SLURP module table "
            "(owner decisions 73(b) and 75). Model-free: reads only sealed bytes."
        ),
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__,
    )
    parser.add_argument("--stage", choices=STAGES, default="all",
                        help="which stage to run (default: all)")
    parser.add_argument("--data-root", type=Path, default=None,
                        help="SPEECHRL_DATA_DIR (default: the environment variable)")
    parser.add_argument("--out-dir", type=Path, default=None,
                        help="where the stage artefacts are written (default: "
                             "<data-root>/analysis/SAEA-SLURP-STAGE3-PRELUDE-V1/frontier)")
    parser.add_argument("--self-check", action="store_true",
                        help="recompute two pinned numbers from the sealed bytes and exit "
                             "non-zero on a mismatch")
    args = parser.parse_args(argv)

    import os

    data_root = args.data_root or Path(os.environ.get("SPEECHRL_DATA_DIR", ""))
    if not data_root or not data_root.is_dir():
        parser.error("--data-root (or SPEECHRL_DATA_DIR) must name an existing directory")
    out_dir = args.out_dir or (
        data_root / "analysis" / "SAEA-SLURP-STAGE3-PRELUDE-V1" / "frontier"
    )

    if args.self_check:
        return 1 if self_check(data_root) else 0

    out_dir.mkdir(parents=True, exist_ok=True)
    collected_path = out_dir / "collect.json"
    frontier_path = out_dir / "frontier.json"
    report_path = out_dir / "frontier-tables.md"

    if args.stage in ("collect", "all"):
        collected = collect(data_root)
        collected_path.write_text(
            json.dumps(collected, ensure_ascii=False, indent=1, sort_keys=True) + "\n",
            encoding="utf-8", newline="\n",
        )
        print(f"collect -> {collected_path} ({len(collected['rows'])} cells)")
        proxies = [r["cell_id"] for r in collected["rows"]
                   if r["cost"]["prefilled_tokens_kind"] != "verdict-measured"]
        print(f"  prefilled-token PROXY rows ({len(proxies)}): {', '.join(proxies)}")
        mismatches = [r["cell_id"] for r in collected["rows"]
                      if r["per_scenario_cross_check"].get("checked")
                      and not r["per_scenario_cross_check"].get("agrees_1e-9")]
        print(f"  per-scenario cross-check mismatches: {mismatches or 'none'}")

    if args.stage in ("frontier", "all"):
        collected = json.loads(collected_path.read_text(encoding="utf-8"))
        front = build_frontier(collected)
        frontier_path.write_text(
            json.dumps(front, ensure_ascii=False, indent=1, sort_keys=True) + "\n",
            encoding="utf-8", newline="\n",
        )
        print(f"frontier -> {frontier_path}")
        for plane, block in front["planes"].items():
            if "frontier" in block:
                print(f"  [{plane}] frontier: {block['frontier']}")
                if isinstance(block.get("knee"), dict) and block["knee"].get("knee"):
                    print(f"  [{plane}] knee: {block['knee']['knee']}")

    if args.stage in ("report", "all"):
        collected = json.loads(collected_path.read_text(encoding="utf-8"))
        front = json.loads(frontier_path.read_text(encoding="utf-8"))
        text = report(collected, front)
        report_path.write_text(text, encoding="utf-8", newline="\n")
        print(f"report -> {report_path}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
