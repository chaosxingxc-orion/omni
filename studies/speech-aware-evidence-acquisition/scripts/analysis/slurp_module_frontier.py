#!/usr/bin/env python3
"""The effect-cost Pareto frontier of the decided SLURP module table.

Owner decisions 73(b) and 75 of 2026-09-21, Stage-3 prelude. Zero model,
tokenizer, encoder, ASR, server, GPU and network contact: this script reads
only bytes that are already sealed -- the repository's own
``docs/receipts/harness-admission.json`` and verdict notes, and, under
``SPEECHRL_DATA_DIR``, each arm's sealed ``flight-receipts.json``,
``<run>.generation-manifest.json``, ``<run>.scores.json`` and the paired-read
``score-contrasts.json`` / ``per-scenario-tables.json`` its verdict named.
Nothing under ``runs/``, ``attempts/`` or ``prepared/`` is opened for writing.
No utterance text and no gold label is read, printed or persisted.

WHAT IT ANSWERS. Every SLURP native cell decided between 2026-09-17 and
2026-09-21 bought some official SLU-F1 for some inference cost. The table of
verdicts records each cell against ITS OWN comparator and never against the
others, so nothing in the repository yet says which cells are on the
effect-cost frontier and which are dominated. This script puts every decided
cell on one plane and names both sets.

THE ONE METHODOLOGICAL RULE THIS SCRIPT OBEYS. The cells do not share a
comparator: B0/B2/B4a/B4b/B7a/B8b/EFF-1 are read against the sealed dual-store
anchor, B5e against cell B1's arm, B1-notool against cell B1's arm, IDX and
IDXT against cell B1-notool, and B8a against three bases at once. **Deltas
measured against different comparators are never chained.** The frontier is
therefore built on each arm's ABSOLUTE official ``slurp-slu-official-train``
number, which is legitimate because every arm scored the SAME 1,080-row TRAIN
Fold A roster with the SAME registered scorer once through a complete
manifest. The per-cell delta and its CI95 are reported in a SECOND table,
each beside the name of the comparator it was measured against.

Development numbers only (owner decision 28). TRAIN Fold A is an exposed
discovery roster; nothing here is a test claim, a superiority claim or a
generalisation claim, and no published baseline is comparable to these
numbers.

STAGES
  --stage collect    one row per decided cell: absolute official SLU-F1 and
                     intent, the delta and CI95 against its own comparator,
                     GPU hours per 1,080 rows, contacts per row, prefilled
                     tokens per row (verdict-measured where one exists, else
                     the manifest's client prompt tokens per row, flagged as
                     a proxy), status, and the source path of every number.
  --stage frontier   the Pareto frontier of (absolute official SLU-F1) against
                     (GPU-h per 1,080) and against (prefilled tokens per row),
                     pooled and per scenario, with the knee and the dominated
                     cells named.
  --stage report     the Markdown tables.
  --stage all        collect, then frontier, then report.
  --self-check       recompute two pinned numbers from the sealed bytes and
                     refuse on a mismatch (see SELF_CHECK below).

USAGE
  PYTHONDONTWRITEBYTECODE=1 PYTHONPATH=<repo>/src \\
  python scripts/analysis/slurp_module_frontier.py --stage all \\
      --data-root "$SPEECHRL_DATA_DIR" \\
      --out-dir "$SPEECHRL_DATA_DIR/analysis/SAEA-SLURP-STAGE3-PRELUDE-V1/frontier"

Every table in docs/results/2026-09-21-slurp-stage3-prelude-frontier-and-verifier-v1.md
is regenerated by that one command.
"""

